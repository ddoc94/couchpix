// ── Derived helpers ──────────────────────────────────────────────────────────

// Alias kept for any existing imports.
export const ALL_QUESTIONS = QUESTIONS;

// Returns a random question that isn't `currentText`, so consecutive picks
// never repeat. Falls back gracefully for tiny pools.
export function pickRandomQuestion(currentText = "") {
  if (QUESTIONS.length === 0) return "";
  if (QUESTIONS.length === 1) return QUESTIONS[0];
  let q;
  do {
    q = QUESTIONS[Math.floor(Math.random() * QUESTIONS.length)];
  } while (q === currentText);
  return q;
}

// ── Shuffle bag ───────────────────────────────────────────────────────────────
// Draws questions with no repeats until the whole library is exhausted, then
// reshuffles. Implemented as random-without-replacement: we track which
// questions have been "seen" this cycle and only draw from the remainder.
//
// State shape: { seen: string[] }  — the questions served so far this cycle.
// drawFromBag returns { question, nextState }; persist nextState to continue
// the bag later (across sessions / devices).
//
// Storing strings (not indices) makes this robust to library edits: a newly
// added question simply enters the remainder immediately, and a removed one
// just never appears. The only cross-cycle repeat guard is `lastQuestion`,
// which is excluded right after a reshuffle so the boundary never repeats.
export function drawFromBag(state, lastQuestion = "") {
  const all = ALL_QUESTIONS;
  if (all.length === 0) return { question: "", nextState: { seen: [] } };
  if (all.length === 1) return { question: all[0], nextState: { seen: [all[0]] } };

  let seen = Array.isArray(state?.seen) ? state.seen : [];
  const seenSet = new Set(seen);
  let remaining = all.filter(q => !seenSet.has(q));

  if (remaining.length === 0) {
    // Bag exhausted — reshuffle. Reset seen, but exclude the last-served
    // question so we don't repeat across the cycle boundary.
    seen = [];
    remaining = all.filter(q => q !== lastQuestion);
    if (remaining.length === 0) remaining = [...all]; // tiny-pool safety
  }

  const question = remaining[Math.floor(Math.random() * remaining.length)];
  return { question, nextState: { seen: [...seen, question] } };
}
